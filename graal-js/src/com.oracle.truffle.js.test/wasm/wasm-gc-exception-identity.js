/**
 * Exported Wasm GC objects retain their JavaScript identity when thrown through a Wasm frame.
 *
 * @option webassembly
 * @option wasm.GC
 */

load('../js/assert.js');

// (module
//   (type $struct (struct (field i32)))
//   (type $array (array i32))
//   (import "" "thrower" (func $thrower (param externref)))
//   (func (export "through") (param externref)
//     local.get 0
//     call $thrower)
//   (func (export "mk_struct") (result anyref)
//     i32.const 1
//     struct.new $struct)
//   (func (export "mk_array") (result anyref)
//     i32.const 2
//     i32.const 3
//     array.new $array))
const bytes = new Uint8Array([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x10, 0x04, 0x5f, 0x01, 0x7f, 0x00, 0x5e, 0x7f, 0x00,
    0x60, 0x01, 0x6f, 0x00, 0x60, 0x00, 0x01, 0x6e,
    0x02, 0x0c, 0x01, 0x00, 0x07, 0x74, 0x68, 0x72, 0x6f, 0x77,
    0x65, 0x72, 0x00, 0x02,
    0x03, 0x04, 0x03, 0x02, 0x03, 0x03,
    0x07, 0x22, 0x03, 0x07, 0x74, 0x68, 0x72, 0x6f, 0x75, 0x67, 0x68,
    0x00, 0x01, 0x09, 0x6d, 0x6b, 0x5f, 0x73, 0x74, 0x72, 0x75, 0x63,
    0x74, 0x00, 0x02, 0x08, 0x6d, 0x6b, 0x5f, 0x61, 0x72, 0x72, 0x61,
    0x79, 0x00, 0x03,
    0x0a, 0x1a, 0x03, 0x06, 0x00, 0x20, 0x00, 0x10, 0x00, 0x0b,
    0x07, 0x00, 0x41, 0x01, 0xfb, 0x00, 0x00, 0x0b,
    0x09, 0x00, 0x41, 0x02, 0x41, 0x03, 0xfb, 0x06, 0x01, 0x0b,
]);

const exports = new WebAssembly.Instance(new WebAssembly.Module(bytes), {
    "": {thrower: value => { throw value; }},
}).exports;

for (const value of [exports.mk_struct(), exports.mk_array()]) {
    for (let i = 0; i < 2; i++) {
        try {
            exports.through(value);
            fail("thrower returned normally");
        } catch (caught) {
            assertTrue(caught === value);
        }
    }
}
