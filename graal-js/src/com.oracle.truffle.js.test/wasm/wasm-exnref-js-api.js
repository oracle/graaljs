load('../js/assert.js');

// (module
//   (import "" "marker" (func $marker))
//   (func (export "result") (result exnref)
//     call $marker
//     ref.null exn))
const resultBytes = new Uint8Array([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x08, 0x02, 0x60, 0x00, 0x00, 0x60, 0x00, 0x01, 0x69,
    0x02, 0x0b, 0x01, 0x00, 0x06, 0x6d, 0x61, 0x72, 0x6b, 0x65, 0x72,
    0x00, 0x00,
    0x03, 0x02, 0x01, 0x01,
    0x07, 0x0a, 0x01, 0x06, 0x72, 0x65, 0x73, 0x75, 0x6c, 0x74, 0x00,
    0x01,
    0x0a, 0x08, 0x01, 0x06, 0x00, 0x10, 0x00, 0xd0, 0x69, 0x0b,
]);
let wasmFunctionCalled = false;
const result = new WebAssembly.Instance(new WebAssembly.Module(resultBytes), {
    "": {marker: () => { wasmFunctionCalled = true; }},
}).exports.result;

assertThrows(() => result(), TypeError);
assertFalse(wasmFunctionCalled);

// (module
//   (import "" "host" (func $host (param exnref)))
//   (func (export "run")
//     ref.null exn
//     call $host))
const parameterBytes = new Uint8Array([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x01, 0x08, 0x02, 0x60, 0x01, 0x69, 0x00, 0x60, 0x00, 0x00,
    0x02, 0x09, 0x01, 0x00, 0x04, 0x68, 0x6f, 0x73, 0x74, 0x00, 0x00,
    0x03, 0x02, 0x01, 0x01,
    0x07, 0x07, 0x01, 0x03, 0x72, 0x75, 0x6e, 0x00, 0x01,
    0x0a, 0x08, 0x01, 0x06, 0x00, 0xd0, 0x69, 0x10, 0x00, 0x0b,
]);
let hostFunctionCalled = false;
const run = new WebAssembly.Instance(new WebAssembly.Module(parameterBytes), {
    "": {host: () => { hostFunctionCalled = true; }},
}).exports.run;

assertThrows(() => run(), TypeError);
assertFalse(hostFunctionCalled);

// (module
//   (table (export "table") 1 exnref))
const tableBytes = new Uint8Array([
    0x00, 0x61, 0x73, 0x6d, 0x01, 0x00, 0x00, 0x00,
    0x04, 0x04, 0x01, 0x69, 0x00, 0x01,
    0x07, 0x09, 0x01, 0x05, 0x74, 0x61, 0x62, 0x6c, 0x65, 0x01, 0x00,
]);
const table = new WebAssembly.Instance(new WebAssembly.Module(tableBytes)).exports.table;
let indexConverted = false;
const index = {valueOf: () => { indexConverted = true; return 0; }};

assertThrows(() => table.get(index), TypeError);
assertFalse(indexConverted);
assertThrows(() => table.set(index), TypeError);
assertFalse(indexConverted);
